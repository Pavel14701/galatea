from abc import ABC, abstractmethod


class Prism(ABC):
    """
    Абстрактный базовый класс для всех Призм.
    Определяет интерфейс вычисления оценки, обновления состояния и сброса.
    """

    @abstractmethod
    def forward(self, *args, **kwargs) -> float:
        """
        Вычисляет скалярную оценку Призмы на текущем шаге.
        Конкретные аргументы зависят от реализации.
        Возвращает float в диапазоне [0, 1].
        """
        pass

    @abstractmethod
    def update(self, *args, **kwargs) -> None:
        """
        Обновляет внутреннее состояние Призмы (если есть)
        на основе нового шага. Например, для SP добавляет
        эмбеддинг в историю, для BP – обучает GRU.
        """
        pass

    @abstractmethod
    def reset(self) -> None:
        """Полностью сбрасывает состояние Призмы
        (новый пользователь или сессия).
        """
        pass
